import pandas as pd

# Load the uploaded file
df = pd.read_csv("NZ_report.csv")

# Ensure correct columns
df = df[["MMS Id", "OCLC Control Number (035a)", "Institution Name", "Title"]]

library_counts = df.groupby("OCLC Control Number (035a)")["Institution Name"].nunique()
oclc_3plus = library_counts[library_counts >= 3].index

df_3plus = df[df["OCLC Control Number (035a)"].isin(oclc_3plus)]
result_3plus = df_3plus.groupby("OCLC Control Number (035a)").agg({
    "Title": "first",
    "MMS Id": lambda x: ", ".join(sorted(set(x.astype(str)))),
    "Institution Name": lambda x: ", ".join(sorted(set(x)))
}).reset_index()

result_3plus.columns = ["OCLC Control Number", "Title", "MMSIDs", "Libraries"]
result_3plus.to_csv("books_with_3plus_copies.csv", index=False)

oclc_less = library_counts[library_counts < 3].index

df_less = df[df["OCLC Control Number (035a)"].isin(oclc_less)]
result_less = df_less.groupby("OCLC Control Number (035a)").agg({
    "Title": "first",
    "MMS Id": lambda x: ", ".join(sorted(set(x.astype(str)))),
    "Institution Name": lambda x: ", ".join(sorted(set(x)))
}).reset_index()

result_less.columns = ["OCLC Control Number", "Title", "MMSIDs", "Libraries"]
result_less.to_csv("books_with_less_than_3_copies.csv", index=False)

